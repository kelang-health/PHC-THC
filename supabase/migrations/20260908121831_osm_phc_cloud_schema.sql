-- OSM PHC Cloud schema for Supabase
-- No Thai citizen 13-digit identifier is stored in this schema.
-- JHCIS person linkage uses source_pcucode + source_pid only.

create extension if not exists pgcrypto with schema extensions;

create extension if not exists postgis with schema extensions;

create schema if not exists private;

revoke all on schema private from public, anon, authenticated;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null check (role in ('admin','coordinator','viewer','volunteer')),
  community text not null default '',
  volunteer_pid bigint,
  active boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.communities (
  id bigint generated by default as identity primary key,
  moo text not null default '',
  name text not null unique,
  active boolean not null default true,
  geometry_geojson jsonb,
  geom extensions.geometry(MultiPolygon,4326),
  source text not null default 'j-report',
  source_hash text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.tambon_boundaries (
  tambon_code text primary key,
  tambon_name_th text not null,
  amphoe_code text not null default '',
  province_code text not null default '',
  geometry_geojson jsonb not null,
  geom extensions.geometry(MultiPolygon,4326),
  source text not null default 'DPM_TH_Boundary',
  source_hash text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.volunteers (
  id uuid primary key default extensions.gen_random_uuid(),
  source_pcucode text not null default '',
  source_pid bigint not null,
  display_name text not null,
  community text not null default '',
  moo text not null default '',
  anchor_hcode text not null default '',
  anchor_latitude double precision,
  anchor_longitude double precision,
  anchor_status text not null default 'missing' check (anchor_status in ('confirmed','community_review','outside_tambon','missing')),
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  unique(source_pcucode, source_pid)
);

create table if not exists public.houses (
  id uuid primary key default extensions.gen_random_uuid(),
  source_pcucode text not null default '',
  hcode text not null,
  house_no text not null default '',
  moo text not null default '',
  community text not null default '',
  latitude double precision,
  longitude double precision,
  geom extensions.geometry(Point,4326),
  coordinate_source text not null default 'none' check (coordinate_source in ('jhcis','sheet','none')),
  coordinate_status text not null default 'missing',
  coordinate_distance_m double precision,
  inside_tambon boolean,
  inside_community boolean,
  volunteer_pid bigint,
  record_status text not null default '',
  review_required boolean not null default false,
  review_reason text not null default '',
  updated_at timestamptz not null default now(),
  unique(source_pcucode, hcode)
);

create table if not exists public.sync_runs (
  id bigint generated by default as identity primary key,
  source text not null,
  app_version text not null default '',
  status text not null check (status in ('running','success','failed')),
  summary jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

