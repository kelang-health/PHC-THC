-- Profiles: users can read their own profile; admins can read/manage all profiles.
drop policy if exists profiles_select on public.profiles;

create policy profiles_select on public.profiles for select to authenticated
using (user_id = auth.uid() or private.current_role() = 'admin');

drop policy if exists profiles_admin_all on public.profiles;

create policy profiles_admin_all on public.profiles for all to authenticated
using (private.current_role() = 'admin')
with check (private.current_role() = 'admin');

-- Tambon boundary is visible to every active authenticated profile.
drop policy if exists tambon_select on public.tambon_boundaries;

create policy tambon_select on public.tambon_boundaries for select to authenticated
using (private.current_role() is not null);

-- Communities are scoped to the user's area. Admin sees all.
drop policy if exists communities_select on public.communities;

create policy communities_select on public.communities for select to authenticated
using (
  private.current_role() = 'admin'
  or name = private.current_community()
);

-- Volunteers are scoped by community; volunteer can always see own record.
drop policy if exists volunteers_select on public.volunteers;

create policy volunteers_select on public.volunteers for select to authenticated
using (
  private.current_role() = 'admin'
  or community = private.current_community()
  or source_pid = private.current_volunteer_pid()
);

-- Houses follow community scope; volunteer only sees assigned houses.
drop policy if exists houses_select on public.houses;

create policy houses_select on public.houses for select to authenticated
using (
  private.current_role() = 'admin'
  or (
    private.current_role() in ('coordinator','viewer')
    and community = private.current_community()
  )
  or (
    private.current_role() = 'volunteer'
    and volunteer_pid = private.current_volunteer_pid()
  )
);

-- Sync metadata and app settings.
drop policy if exists sync_runs_admin_select on public.sync_runs;

create policy sync_runs_admin_select on public.sync_runs for select to authenticated
using (private.current_role() = 'admin');

drop policy if exists app_settings_select on public.app_settings;

create policy app_settings_select on public.app_settings for select to authenticated
using (private.current_role() is not null);

