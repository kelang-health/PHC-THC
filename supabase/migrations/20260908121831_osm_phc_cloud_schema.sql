create or replace function private.set_house_geom()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.latitude is null or new.longitude is null then
    new.geom := null;
  elsif new.latitude between -90 and 90 and new.longitude between -180 and 180 then
    new.geom := extensions.st_setsrid(extensions.st_makepoint(new.longitude, new.latitude),4326);
  else
    raise exception 'invalid latitude/longitude';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create or replace function private.set_boundary_geom()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.geometry_geojson is null then
    new.geom := null;
  else
    new.geom := extensions.st_multi(
      extensions.st_setsrid(
        extensions.st_geomfromgeojson(new.geometry_geojson::text),4326
      )
    );
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create or replace trigger trg_houses_geom
before insert or update of latitude, longitude on public.houses
for each row execute function private.set_house_geom();

create or replace trigger trg_communities_geom
before insert or update of geometry_geojson on public.communities
for each row execute function private.set_boundary_geom();

create or replace trigger trg_tambon_geom
before insert or update of geometry_geojson on public.tambon_boundaries
for each row execute function private.set_boundary_geom();

create or replace function private.current_role()
returns text
language sql stable security definer
set search_path = ''
as $$
  select p.role from public.profiles p
  where p.user_id = auth.uid() and p.active = true
  limit 1
$$;

create or replace function private.current_community()
returns text
language sql stable security definer
set search_path = ''
as $$
  select p.community from public.profiles p
  where p.user_id = auth.uid() and p.active = true
  limit 1
$$;

create or replace function private.current_volunteer_pid()
returns bigint
language sql stable security definer
set search_path = ''
as $$
  select p.volunteer_pid from public.profiles p
  where p.user_id = auth.uid() and p.active = true
  limit 1
$$;

revoke all on function private.current_role() from public, anon, authenticated;

revoke all on function private.current_community() from public, anon, authenticated;

